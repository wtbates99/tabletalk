"""The lock file: a reviewed snapshot of exactly what each agent is approved to see.

``tabletalk.lock.yaml`` plays the role of Terraform state. It records, per agent, the
resolved dbt resources, their columns, column types, description digests, sensitivity,
and attached tests. ``tabletalk plan`` compares it with the current manifest.

The file has no timestamps and no manifest digest, so it changes only when an agent's
world changes. That keeps git diffs of the lock meaningful in code review.
"""

from __future__ import annotations

from pathlib import Path
from typing import Literal

import yaml
from pydantic import BaseModel, ConfigDict, ValidationError

from tabletalk.agents import Agent
from tabletalk.manifest import Manifest, Node
from tabletalk.schemas import LOCK_SCHEMA, content_digest
from tabletalk.semantic_guard import is_sensitive

LOCK_FILENAME = "tabletalk.lock.yaml"


class LockError(ValueError):
    """The lock file is missing required structure or has an unsupported schema."""


class _Frozen(BaseModel):
    model_config = ConfigDict(frozen=True, extra="forbid")


class ColumnState(_Frozen):
    """What an agent knows about one column."""

    data_type: str | None
    description_digest: str
    sensitive: bool


class ResourceState(_Frozen):
    """What an agent knows about one dbt resource."""

    name: str
    relation_name: str
    checksum: str | None
    description_digest: str
    columns: dict[str, ColumnState]
    tests: list[str]


class AgentState(_Frozen):
    """The resolved scope of one agent at lock time."""

    agent_digest: str
    select: list[str]
    exclude: list[str]
    resources: dict[str, ResourceState]


class LockFile(_Frozen):
    """The full lock: every agent's approved scope, keyed by agent name."""

    schema_version: Literal["tabletalk.lock/v1"] = "tabletalk.lock/v1"
    agents: dict[str, AgentState]


def _digest(text: str) -> str:
    """Return a short, stable digest for a description; full text lives in dbt."""
    return content_digest(text.strip())[:23]


def resource_state(node: Node) -> ResourceState:
    """Snapshot one manifest node as the agent sees it."""
    return ResourceState(
        name=node.name,
        relation_name=node.relation_name or f"{node.schema}.{node.alias}".strip("."),
        checksum=node.checksum,
        description_digest=_digest(node.description),
        columns={
            name: ColumnState(
                data_type=column.physical_type or column.data_type,
                description_digest=_digest(column.description),
                sensitive=is_sensitive(node, name),
            )
            for name, column in sorted(node.columns.items())
        },
        tests=sorted(test.unique_id for test in node.tests),
    )


def snapshot(agents: tuple[Agent, ...], manifest: Manifest) -> LockFile:
    """Resolve every agent against the manifest and record its scope."""
    states: dict[str, AgentState] = {}
    for agent in sorted(agents, key=lambda item: item.name):
        resolved = agent.resolve(manifest)
        states[agent.name] = AgentState(
            agent_digest="sha256:" + agent.digest,
            select=list(agent.select),
            exclude=list(agent.exclude),
            resources={
                node.unique_id: resource_state(node)
                for node in sorted(resolved.nodes, key=lambda item: item.unique_id)
            },
        )
    return LockFile(agents=states)


def dump_lock(lock: LockFile) -> str:
    """Render the lock as deterministic, human-readable YAML."""
    header = (
        "# Generated by `tabletalk lock`. Review changes to this file like code.\n"
        "# It records exactly what each agent was approved to see.\n"
    )
    body = yaml.safe_dump(lock.model_dump(mode="json"), sort_keys=True, allow_unicode=True)
    return header + body


def write_lock(path: Path, lock: LockFile) -> None:
    """Write the lock file atomically enough for a CLI: one full rewrite."""
    path.write_text(dump_lock(lock), encoding="utf-8")


def load_lock(path: Path) -> LockFile | None:
    """Load the lock file, or return ``None`` when the project has not been locked yet."""
    if not path.is_file():
        return None
    try:
        payload = yaml.safe_load(path.read_text(encoding="utf-8"))
        return LockFile.model_validate(payload)
    except (yaml.YAMLError, ValidationError) as exc:
        raise LockError(f"{path} is not a valid {LOCK_SCHEMA} file: {exc}") from exc


def refresh_agents(
    lock: LockFile | None, agents: tuple[Agent, ...], manifest: Manifest
) -> LockFile:
    """Return ``lock`` with only the given agents re-snapshotted.

    Approval accepts the reviewed agents' current scope. Every other agent keeps its
    locked entry, so approving one agent never silently accepts drift in another.
    """
    fresh = snapshot(agents, manifest).agents
    merged = {**(lock.agents if lock else {}), **fresh}
    return LockFile(agents=dict(sorted(merged.items())))
